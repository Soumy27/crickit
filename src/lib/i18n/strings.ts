/**
 * The app's words, in the ten languages the speech models cover.
 *
 * Two deliberate limits:
 *
 *  - This covers the *app* — the screens a scorer uses at a ground. Those
 *    strings are short and factual ("Runs", "Not out", "Who is bowling?"),
 *    which is exactly the kind of text that survives translation. The
 *    landing page's prose stays in English rather than being machine-turned
 *    into nine languages nobody here can proofread.
 *  - Anything missing from a language falls back to English rather than
 *    rendering blank, so a half-filled dictionary degrades instead of
 *    breaking.
 *
 * Cricket vocabulary across India is largely the English word in the local
 * script — "रन", "ವಿಕೆಟ್", "ওভার". That is how people actually speak at a
 * maidan, so it is what is written here; inventing purer alternatives would
 * make the app less readable, not more Indian.
 */

